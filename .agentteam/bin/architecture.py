#!/usr/bin/env python3
"""architecture.py — regenerate ARCHITECTURE.md from the live harness.

Every number on the page is computed from roster.json, pipeline.json, budgets.json and the
gate.py check registry, so the reference document cannot drift from the code.

  python architecture.py          write ARCHITECTURE.md
  python architecture.py --check  exit 1 if ARCHITECTURE.md is stale
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import List

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _lib as L  # noqa: E402
import gate as G  # noqa: E402


def render() -> str:
    roster, pipe, budgets, pol = (L.load_config(n) for n in ("roster", "pipeline", "budgets", "policy"))
    teams = roster["teams"]
    n_ics = sum(len(t["ics"]) for t in teams)
    n_agents = len(teams) + n_ics
    gates = [g for p in pipe["phases"] for g in p["gates"]]
    out: List[str] = [
        "# Agent Team Harness — architecture",
        "",
        "_Generated by `python .agentteam/bin/architecture.py` from the live harness. Do not edit by hand; "
        "the design rationale is in [DESIGN.md](DESIGN.md)._",
        "",
        "**Software delivery, run by agents, governed by checks.** Seven teams take a story from request to "
        "deployment. Nothing advances because an agent said it was done.",
        "",
        "| Teams | Agents | Phases | Gates | Checks | Human gates |",
        "|---|---|---|---|---|---|",
        f"| {len(teams)} | {n_agents} | {len(pipe['phases'])} | {len(gates)} | {len(G.REGISTRY)} | {len(pipe['human_gates'])} |",
        "",
        f"{len(teams)} leads on `{roster['models']['lead']}`, {n_ics} ICs on `{roster['models']['ic']}`.",
        "",
        "## Structure",
        "",
        "```",
        "Supervisor (human) — owns the human gates",
        "  └─ Claude (main session) — manages the leads laterally; produces nothing itself",
    ]
    for t in teams:
        out.append(f"       ├─ {t['title']:<8} {t['lead']['id']:<12} → {len(t['ics'])} ICs: {', '.join(i['id'] for i in t['ics'])}")
    out += ["```", "",
            "An IC reports to its lead, never past it, so a challenge is resolved inside the team that raised it.",
            "", "## Teams — least privilege is structural, not advisory", "",
            "| Team | Lead | ICs | Bash profile | Write roots |", "|---|---|---|---|---|"]
    for t in teams:
        roots = ", ".join(f"`{r}`" for r in t["write_roots"]) or "read-only by design"
        out.append(f"| `{t['id']}` | {t['lead']['id']} | {len(t['ics'])} | {t['bash_profile']} | {roots} |")
    out += ["", "QA writes test files only; dev may not write acceptance tests, snapshots or golden files "
            f"(`{'`, `'.join(pol['protected_from_dev'])}`). The review team writes nothing — its ICs return findings "
            "and the lead records them through `story.py`.",
            "", "## Pipeline", "", "| Phase | Team | Writes | Reads (packet) | Gates | Human gate after |", "|---|---|---|---|---|---|"]
    for p in pipe["phases"]:
        hum = [L.human_gate_after(g)["id"] for g in p["gates"] if L.human_gate_after(g)]
        out.append(f"| {p['n']} {p['title']} | {p['team']} | {', '.join(p['writes']) or '—'} | "
                   f"{', '.join(p['reads']) or '—'} | {', '.join(p['gates'])} | {', '.join(hum) or ''} |")
    caps = ", ".join(f"{k.split('-', 1)[1]} {v}" for k, v in pipe["round_caps"].items())
    out += ["", "Loops: " + "; ".join(f"{l['from']} → {l['to']} ({l['carries']})" for l in pipe["loops"]) + ".",
            f"Round caps: {caps}. A breached cap stops the story; the loop does not keep running.",
            "", "## Human gates — decisions that are not Claude's to make", "",
            "| Gate | After | Reviews |", "|---|---|---|"]
    for h in pipe["human_gates"]:
        out.append(f"| {h['id']} | {h['after_gate']} | `{h['reviews']}` |")
    out += ["", "`story.py human-gate` needs an interactive terminal and a typed confirmation, and guard.py refuses it to "
            "every agent. Someone with shell access can still forge a record; that is the one place the design trusts "
            "the supervisor, and it is stated here rather than hidden.",
            "", "## Enforcement — three layers, named honestly", "",
            "| Layer | Mechanism | Failure looks like |", "|---|---|---|",
            "| Hard | `guard.py` PreToolUse hook | the tool call never runs |",
            f"| Audited | `gate.py`, {len(G.REGISTRY)} checks over artifacts on disk | the phase does not advance; failures listed |",
            "| Instructed | `.claude/agents/*.md`, packets, the `/story` skill | nothing stops it — the weakest layer, never the only one |",
            "", "guard.py fails open on an internal error so a guard bug can't brick a session, but every error is recorded and "
            "fails every gate of the phase it happened in.",
            f"Hard denies for every role: {', '.join(r['id'] for r in pol['hard_deny_bash'])}, secret paths, git internals, "
            "harness code, audit records, human-only commands, deploys beyond dev without the human gate.",
            "", "## Checks", ""]
    for g in G.GATES:
        cs = G.checks_for(g)
        out.append(f"**{g}** ({len(cs)}): " + "; ".join(c.id.split(".", 1)[1] for c in cs))
        out.append("")
    out += ["## Budgets — a phase has a ceiling, and the gate knows it", "", "| Phase | Agents | Tokens |", "|---|---|---|"]
    for pid, b in budgets["phases"].items():
        out.append(f"| `{pid}` | {b['agents']} | {b['tokens']:,} |")
    out += ["", "Usage is recorded per phase by the SubagentStop hook; a breach fails that phase's gate instead of "
            "turning up later in a bill.",
            "", "## Operating it", "",
            "| Command | What it does |", "|---|---|",
            "| `/add-project` | create, clone or adopt a project repo under `workspace/`, with its smoke suite verified |",
            "| `/story <title>` | run a story through every phase, pausing at each human gate |",
            "| `/architecture` | regenerate this document from the live harness |",
            "| `python .agentteam/bin/selftest.py` | prove the gates still block; run it after touching anything under `.agentteam/` |",
            ""]
    return "\n".join(out)


def main(argv: List[str]) -> int:
    path = L.root() / "ARCHITECTURE.md"
    txt = render()
    if "--check" in argv:
        ok = path.exists() and L.read_text(path) == txt
        print("ARCHITECTURE.md is " + ("current" if ok else "STALE — run architecture.py"))
        return 0 if ok else 1
    L.write_text(path, txt)
    print(f"wrote ARCHITECTURE.md ({len(G.REGISTRY)} checks)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
